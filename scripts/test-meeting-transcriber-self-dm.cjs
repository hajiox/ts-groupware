const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')

const source = fs.readFileSync(path.join(__dirname, '..', 'lib', 'meeting-transcriber-self-dm.ts'), 'utf8')
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText
const loaded = { exports: {} }
new Function('module', 'exports', 'require', output)(loaded, loaded.exports, require)
assert.equal(loaded.exports.normalizeMeetingTranscriberDmName('  佐藤　正彦 '), '佐藤正彦')
assert.equal(loaded.exports.meetingTranscriberSelfDmChatKey('b', 'a'), 'direct:a:b')
const first = loaded.exports.meetingTranscriberSelfDmPostId('meeting:1', 'user-1')
assert.match(first, /^[0-9a-f]{8}-[0-9a-f]{4}-5[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/)
assert.equal(loaded.exports.meetingTranscriberSelfDmPostId('meeting:1', 'user-1'), first)
assert.notEqual(loaded.exports.meetingTranscriberSelfDmPostId('meeting:2', 'user-1'), first)
assert.equal(loaded.exports.requiredMeetingTranscriberDmText(' 要約 ', 'content', 20), '要約')
assert.throws(() => loaded.exports.requiredMeetingTranscriberDmText('', 'content', 20), /content is invalid/)

const route = fs.readFileSync(path.join(__dirname, '..', 'app', 'api', 'integrations', 'meeting-transcriber', 'self-dm', 'route.ts'), 'utf8')
const proxy = fs.readFileSync(path.join(__dirname, '..', 'proxy.ts'), 'utf8')
assert.match(route, /MEETING_TRANSCRIBER_INTEGRATION_SECRET/)
assert.match(route, /MEETING_TRANSCRIBER_DM_RECIPIENT_NAME/)
assert.doesNotMatch(route, /body\.recipientName/)
assert.match(route, /Direct-message group member verification failed/)
assert.match(route, /sendPushNotificationToUser/)
assert.match(proxy, /['\"]\/api\/integrations\/meeting-transcriber\/summary['\"]/)
assert.match(proxy, /['\"]\/api\/integrations\/meeting-transcriber\/self-dm['\"]/)
assert.doesNotMatch(proxy, /^\s*['"]\/api\/integrations\/meeting-transcriber['"],?\s*$/m)
assert.match(route, /kind: 'self'/)
console.log('MeetingTranscriber self-DM integration checks passed.')
